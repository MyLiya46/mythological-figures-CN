//  十方救苦天尊、五方五帝 —— 道教《玉皇经》《周礼·天官》及纬书
// ============================================================================
const Ns = [];
const Es = [];
const N = (id, name, category, level, desc, aliases = [], shape) =>
  Ns.push({ id, name, category, level, desc, aliases, shape });
const E = (source, target, type, desc) => Es.push({ source, target, type, desc });

// ---- 六十甲子值年太岁（天干地支纪年，固定序列）----
const gan = '甲乙丙丁戊己庚辛壬癸';
const zhi = '子丑寅卯辰巳午未申酉戌亥';
let g = 0, z = 0;
for (let i = 0; i < 60; i++) {
  const name = gan[g] + zhi[z] + '太岁';
  const id = 'sj_' + i;
  N(id, name, 'daojiao', 3, `${gan[g]}${zhi[z]}年之值年太岁神，主该年吉凶（道教太岁信仰）。`, [], 'god');
  Es.push({ source: 'taiyi_zhuishen', target: id, type: 'subordinate', desc: `${name}为总太岁所统六十甲子神之一。` });
  g = (g + 1) % 10; z = (z + 1) % 12;
}

