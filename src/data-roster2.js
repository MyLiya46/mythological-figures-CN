  '虚明堂曜天','观明端靖天','玄明恭庆天','太焕极瑶天','元载孔升天','太安皇崖天',          // 7-12
  '显定极风天','始黄孝芒天','太黄翁重天','无思江由天','上揲阮乐天','无极昙誓天',          // 13-18
